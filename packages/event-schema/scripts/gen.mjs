#!/usr/bin/env node
// Generates src/generated.ts (TS types + EVENT_TYPES) from schema/ and copies schema/ + fixtures/
// into the Frappe app (frappe-apps/erp_town/erp_town/events/schema/). Deterministic, LF output.
// Usage (repo root): pnpm schema:gen
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(pkgDir, '..', '..')
const schemaDir = join(pkgDir, 'schema')
const fixturesDir = join(pkgDir, 'fixtures')
const generatedTs = join(pkgDir, 'src', 'generated.ts')
const frappeTarget = join(repoRoot, 'frappe-apps', 'erp_town', 'erp_town', 'events', 'schema')

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))
const lf = (s) => s.replace(/\r\n/g, '\n')
const write = (p, s) => {
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, lf(s))
}
const jsonFiles = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
const fail = (msg) => {
  console.error(`schema:gen: ${msg}`)
  process.exit(1)
}

// ---------------------------------------------------------------- load + consistency checks
const envelope = readJson(join(schemaDir, 'envelope.json'))
const eventTypes = envelope.properties.type.enum
const eventFiles = jsonFiles(join(schemaDir, 'events'))
const dispatched = envelope.allOf
  .filter((s) => s.if)
  .map((s) => [s.if.properties.type.const, s.then.properties.data.$ref])

const sameSet = (a, b) =>
  a.length === b.length && [...a].sort().join('\n') === [...b].sort().join('\n')
if (
  !sameSet(
    eventTypes,
    eventFiles.map((f) => f.replace(/\.json$/, '')),
  )
) {
  fail('envelope type enum and schema/events/*.json files differ')
}
if (
  !sameSet(
    eventTypes,
    dispatched.map(([t]) => t),
  )
) {
  fail('envelope type enum and envelope allOf data dispatch differ')
}
for (const [t, ref] of dispatched) {
  if (ref !== `events/${t}.json`) fail(`dispatch for ${t} must $ref events/${t}.json (got ${ref})`)
  const s = readJson(join(schemaDir, 'events', `${t}.json`))
  if (s.$id !== `https://erp-town.local/schema/events/${t}.json`)
    fail(`bad $id in events/${t}.json`)
}

// ---------------------------------------------------------------- TS types
const VALIDATION_ONLY = new Set(['if', 'then', 'else', 'allOf', '$id', '$schema', 'title'])
// Remove keywords that only refine validation (and confuse json-schema-to-typescript).
const strip = (node) => {
  if (Array.isArray(node)) return node.map(strip)
  if (node === null || typeof node !== 'object') return node
  return Object.fromEntries(
    Object.entries(node)
      .filter(([k]) => !VALIDATION_ONLY.has(k))
      .map(([k, v]) => [k, k === 'properties' || k === '$defs' ? mapValues(v, strip) : strip(v)]),
  )
}
const mapValues = (obj, fn) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v)]))
const pascal = (s) =>
  s
    .split(/[._]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('')

const options = {
  bannerComment: '',
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: false,
  format: true,
  cwd: schemaDir,
}

const env = strip(envelope)
delete env.properties.type
delete env.properties.data
env.required = env.required.filter((k) => k !== 'type' && k !== 'data')
env.$defs = {
  actor: env.$defs.actor,
  subject: env.$defs.subject,
  visibility: env.$defs.visibility,
  ulid: env.$defs.ulid,
}

const parts = [await compile(env, 'TownEventEnvelope', options)]
const dataNames = []
for (const t of eventTypes) {
  const name = `${pascal(t)}Data`
  dataNames.push([t, name])
  parts.push(await compile(strip(readJson(join(schemaDir, 'events', `${t}.json`))), name, options))
}

const ts = `// GENERATED by packages/event-schema/scripts/gen.mjs — do not edit. Run \`pnpm schema:gen\`.
// Source of truth: packages/event-schema/schema/*.json

export const EVENT_TYPES = ${JSON.stringify(eventTypes, null, 2).replace(/"/g, "'")} as const

export type EventType = (typeof EVENT_TYPES)[number]

${parts.join('\n')}
export interface EventDataMap {
${dataNames.map(([t, n]) => `  '${t}': ${n}`).join('\n')}
}

export type TownEventOf<T extends EventType> = TownEventEnvelope & { type: T; data: EventDataMap[T] }

/** A town event: the envelope with \`type\` and \`data\` narrowed per event type. */
export type TownEvent = { [T in EventType]: TownEventOf<T> }[EventType]
`
write(generatedTs, ts)

// ---------------------------------------------------------------- copy into the Frappe app
rmSync(frappeTarget, { recursive: true, force: true })
const copyJsonDir = (from, to) => {
  for (const f of jsonFiles(from)) write(join(to, f), readFileSync(join(from, f), 'utf8'))
}
write(join(frappeTarget, 'envelope.json'), readFileSync(join(schemaDir, 'envelope.json'), 'utf8'))
copyJsonDir(join(schemaDir, 'events'), join(frappeTarget, 'events'))
copyJsonDir(join(fixturesDir, 'valid'), join(frappeTarget, 'fixtures', 'valid'))
copyJsonDir(join(fixturesDir, 'invalid'), join(frappeTarget, 'fixtures', 'invalid'))
write(
  join(frappeTarget, 'README.md'),
  `# GENERATED — edit packages/event-schema

Do not edit files in this directory. They are copied from \`packages/event-schema/\` by
\`pnpm schema:gen\` (run from the repo root); edit the source there and re-run the command.

- \`envelope.json\` — event envelope (JSON Schema 2020-12), \`$id\` \`https://erp-town.local/schema/envelope.json\`
- \`events/<type>.json\` — \`data\` schema per event type, \`$id\` \`https://erp-town.local/schema/events/<type>.json\`
- \`fixtures/valid/*.json\`, \`fixtures/invalid/*.json\` — golden examples shared with the TS contract test

The envelope references the per-type schemas by relative \`$ref\` (\`events/<type>.json\`), which
resolves against its \`$id\`. A Python consumer must therefore register every schema in a
\`referencing\` registry (keyed by \`$id\`) before validating:

\`\`\`python
import json
from pathlib import Path

from jsonschema import Draft202012Validator
from referencing import Registry, Resource

SCHEMA_DIR = Path(__file__).parent / "schema"  # this directory


def load_validator() -> Draft202012Validator:
    paths = [SCHEMA_DIR / "envelope.json", *sorted((SCHEMA_DIR / "events").glob("*.json"))]
    schemas = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    registry = Registry().with_resources(
        (s["$id"], Resource.from_contents(s)) for s in schemas
    )
    envelope = schemas[0]
    Draft202012Validator.check_schema(envelope)
    return Draft202012Validator(
        envelope,
        registry=registry,
        format_checker=Draft202012Validator.FORMAT_CHECKER,
    )
\`\`\`

Envelope rules (see \`packages/event-schema/README.md\`): \`company\` is the company code (Company
abbr); \`seq\` is per subject across all event types and statuses and has expected gaps (Invalid rows
are never published, \`system.error\` is role-restricted), so consumers never wait for a missing seq.

\`format\` assertions are optional in Python (\`date-time\` needs \`rfc3339-validator\`); the schemas
also carry \`pattern\`s for \`time\` and dates so validation results match ajv either way.
`,
)

const rel = (p) => relative(repoRoot, p).replace(/\\/g, '/')
console.log(`schema:gen: wrote ${rel(generatedTs)} (${eventTypes.length} event types)`)
console.log(`schema:gen: copied schema + fixtures to ${rel(frappeTarget)}`)
